-- PostgreSQL bootstrap: run once in a database without public.tickets.
-- Deliberately fail on existing tables instead of replacing existing data.
BEGIN;

CREATE TABLE public.tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(100) NOT NULL,
    description text NOT NULL DEFAULT '',
    status varchar(20) NOT NULL DEFAULT 'open',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT valid_title CHECK (length(trim(title)) BETWEEN 3 AND 100),
    CONSTRAINT valid_description CHECK (length(description) <= 2000),
    CONSTRAINT valid_status CHECK (status IN ('open', 'in_progress', 'closed'))
);

CREATE INDEX idx_tickets_created ON public.tickets (created_at DESC, id DESC);

COMMIT;
